// Official NFL rosters for the latest week, from NFLverse weekly rosters.
//   node scripts/update-rosters.mjs <season> [roster_weekly csv]
// Writes data/nflverse-rosters-<season>.js: each team's current players with their roster
// status. Players who have left a team (cut, released, traded, retired) are not listed, so
// the roster feed and the ratings can drop stale entries.
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { parseColumns } from "./fit-absence-values.mjs";

export const DEPARTED_STATUSES = new Set(["CUT", "RET", "RLS", "TRD", "TRT", "UFA", "RFA", "ERFA"]);
// On the roster but unable to play: reserve lists, inactive, suspended, exempt.
export const UNAVAILABLE_STATUSES = new Set(["RES", "INA", "SUS", "PUP", "NFI", "EXE"]);
const teamCode = (value) => ({ WAS: "WSH", LA: "LAR", JAC: "JAX", OAK: "LV", SD: "LAC", STL: "LAR" })[String(value || "").toUpperCase()] ||
  String(value || "").toUpperCase();

export function buildRosterArtifact(rows, { season, now = new Date() }) {
  const current = rows.filter((row) => Number(row.season) === season);
  const week = Math.max(...current.map((row) => Number(row.week)).filter(Number.isFinite));
  const teams = {};
  for (const row of current.filter((r) => Number(r.week) === week && !DEPARTED_STATUSES.has(r.status))) {
    (teams[teamCode(row.team)] ||= []).push({ sleeperId: row.sleeper_id || null, gsisId: row.gsis_id || null,
      pfrId: row.pfr_id || null, name: row.full_name, position: row.position, status: row.status });
  }
  for (const list of Object.values(teams)) list.sort((a, b) => a.name.localeCompare(b.name));
  return { schemaVersion: 1, season, week, generatedAt: now.toISOString(), source: "NFLverse weekly rosters",
    teams: Object.fromEntries(Object.entries(teams).sort(([a], [b]) => a.localeCompare(b))) };
}

export function validateRosterArtifact(artifact) {
  const problems = [];
  const teams = Object.keys(artifact.teams || {});
  if (teams.length !== 32) problems.push(`${teams.length} teams`);
  for (const code of teams) {
    const active = artifact.teams[code].filter((player) => player.status === "ACT").length;
    if (active < 45) problems.push(`${code} has ${active} active players`);
  }
  return problems;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const season = Number(process.argv[2]);
  if (!Number.isInteger(season)) throw new Error("Usage: update-rosters.mjs <season> [roster_weekly csv]");
  const text = process.argv[3] ? fs.readFileSync(process.argv[3], "utf8") : await (async () => {
    const url = `https://github.com/nflverse/nflverse-data/releases/download/weekly_rosters/roster_weekly_${season}.csv`;
    const response = await fetch(url, { signal: AbortSignal.timeout(120000) });
    if (!response.ok) throw new Error(`Required dataset unavailable: ${url} (${response.status})`);
    return response.text();
  })();
  const artifact = buildRosterArtifact(parseColumns(text, ["season", "week", "team", "position", "status", "full_name", "gsis_id",
    "sleeper_id", "pfr_id"]), { season });
  const problems = validateRosterArtifact(artifact);
  if (problems.length) throw new Error(`Rosters not ready: ${problems.join(", ")}`);
  const destination = `data/nflverse-rosters-${season}.js`;
  fs.writeFileSync(`${destination}.tmp`, `// Generated by scripts/update-rosters.mjs. Do not edit by hand.\nexport default ${JSON.stringify(artifact)};\n`);
  fs.renameSync(`${destination}.tmp`, destination);
  console.log(`Wrote ${destination}: Week ${artifact.week} rosters, ${Object.values(artifact.teams).flat().length} players`);
}
