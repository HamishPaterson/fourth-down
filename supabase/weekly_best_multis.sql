create table if not exists public.weekly_best_multis (
  id bigint generated by default as identity primary key,
  season integer not null,
  week integer not null check (week between 1 and 18),
  lock_at timestamptz not null,
  locked_at timestamptz not null,
  legs jsonb not null default '[]'::jsonb check (jsonb_typeof(legs) = 'array' and jsonb_array_length(legs) <= 5),
  model_probability_threshold numeric(5, 4) not null check (model_probability_threshold between 0.55 and 0.65),
  status text not null check (status in ('locked', 'partial')),
  partial boolean not null,
  generated_late boolean not null default false,
  odds_late boolean not null default false,
  odds_updated_at timestamptz,
  odds_refreshed_at timestamptz,
  odds_cache_status text not null,
  reason text,
  reason_counts jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  constraint weekly_best_multis_season_week_key unique (season, week),
  constraint weekly_best_multis_status_consistency check (partial = (status = 'partial'))
);

alter table public.weekly_best_multis enable row level security;

revoke all on table public.weekly_best_multis from anon, authenticated, service_role;
grant select, insert on table public.weekly_best_multis to service_role;
grant select on table public.weekly_best_multis to anon, authenticated;
grant usage on schema public to anon, authenticated;

drop policy if exists "weekly_best_multis_client_select" on public.weekly_best_multis;
drop policy if exists "weekly_best_multis_service_role_select" on public.weekly_best_multis;
drop policy if exists "weekly_best_multis_service_role_insert" on public.weekly_best_multis;
create policy "weekly_best_multis_client_select"
  on public.weekly_best_multis for select to anon, authenticated using (true);
create policy "weekly_best_multis_service_role_insert"
  on public.weekly_best_multis for insert to service_role with check (true);

create or replace function public.prevent_weekly_best_multi_mutation()
returns trigger
language plpgsql
set search_path = pg_catalog, public
as $$
begin
	raise exception 'weekly_best_multis records cannot be updated or deleted';
end;
$$;

drop trigger if exists weekly_best_multis_prevent_update on public.weekly_best_multis;
drop trigger if exists weekly_best_multis_prevent_delete on public.weekly_best_multis;
drop trigger if exists weekly_best_multis_prevent_mutation on public.weekly_best_multis;
create trigger weekly_best_multis_prevent_mutation
  before update or delete on public.weekly_best_multis
	for each row execute function public.prevent_weekly_best_multi_mutation();
